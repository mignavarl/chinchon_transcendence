package com.transcendence.backend.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Represents an application user stored in the database.
 * This entity contains basic authentication fields such as
 * username and password. Passwords are stored in hashed form
 * using BCrypt for security.
 */
@Entity
@Table(name = "users")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class User {

    /**
     * Primary key identifier for the user.
     * Automatically generated by the database.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Unique username chosen by the user.
     * Cannot be null and must be unique.
     */
    @Column(nullable = false, unique = true)
    private String username;

    /**
     * Hashed password stored securely using BCrypt.
     * Never stored or returned in plain text.
     */
    @Column(nullable = false)
    private String password;
}
