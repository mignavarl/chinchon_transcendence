package com.transcendence.backend.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Represents an application user stored in the database.
 * This entity contains basic authentication fields such as
 * username and password. Passwords are stored in hashed form
 * using BCrypt for security.
 *
 * El esquema lo define db/init.sql, no Hibernate (ddl-auto=validate).
 * La tabla "users" tiene mas columnas de las que se mapean aqui
 * (email, avatar_url, coins, deck_selected, wins, losses, ...); todas
 * son nullable o tienen DEFAULT, asi que el alta desde el backend
 * funciona sin tocarlas. Si necesitas alguna, mapeala y actualiza
 * init.sql en el mismo commit.
 */
@Entity
@Table(name = "users")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class User {

    /**
     * Primary key identifier for the user.
     * Automatically generated by the database.
     *
     * Integer y no Long: en init.sql es SERIAL (int4) y seis tablas lo
     * referencian como INTEGER.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Integer id;

    /**
     * Unique username chosen by the user.
     * Cannot be null and must be unique.
     */
    @Column(nullable = false, unique = true)
    private String username;

    /**
     * Display name shown at the table. NOT NULL en init.sql y sin DEFAULT,
     * asi que hay que darle valor al crear el usuario.
     */
    @Column(nullable = false)
    private String name;

    /**
     * Hashed password stored securely using BCrypt.
     * Never stored or returned in plain text.
     */
    @Column(name = "password_hash", nullable = false)
    private String password;
}
